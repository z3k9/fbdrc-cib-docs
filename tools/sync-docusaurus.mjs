// Builds the Docusaurus (React) site content from the Mintlify source.
// Usage: node tools/sync-docusaurus.mjs   (run from the repo root)
// Mintlify stays the single source of truth: edit mintlify/, then re-run this.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const SRC = path.join(ROOT, 'mintlify');
const SITE = path.join(ROOT, 'react-site');
const DOCS = path.join(SITE, 'docs');
const cfg = JSON.parse(fs.readFileSync(path.join(SRC, 'docs.json'), 'utf8'));

const rm = (p) => fs.rmSync(p, {recursive: true, force: true});
const copyDir = (a, b) => fs.cpSync(a, b, {recursive: true});

function transform(text, page) {
  // Frontmatter: map Mintlify keys to Docusaurus keys
  text = text.replace(/^---\n([\s\S]*?)\n---\n/, (m, fm) => {
    let out = fm.replace(/^sidebarTitle:/m, 'sidebar_label:');
    // Pin every URL to the Mintlify path (Docusaurus would otherwise turn
    // folder/folder.mdx into /folder)
    out += page === 'index' ? '\nslug: /' : `\nslug: /${page}`;
    return `---\n${out}\n---\n`;
  });
  // Images: let webpack bundle them so paths work under any baseUrl
  text = text.replace(/src="\/(images\/[^"]+)"/g, (m, p) => `src={require('@site/doc-assets/${p}').default}`);
  // Code block titles: ```xml Title  ->  ```xml title="Title"
  text = text.replace(/^(\s*)```(\w+) (?!title=)(.+)$/gm, (m, ind, lang, title) => `${ind}\`\`\`${lang} title="${title.trim()}"`);
  return text;
}

rm(DOCS);
const pages = [];
const sidebars = {};
const tabIds = [];
for (const tab of cfg.navigation.tabs) {
  const id = tab.tab.replace(/[^A-Za-z0-9]+(.)?/g, (m, c) => (c ? c.toUpperCase() : '')).replace(/^./, (c) => c.toLowerCase());
  tabIds.push({id, label: tab.tab, first: tab.groups[0].pages[0]});
  sidebars[id] = tab.groups.map((g) => ({type: 'category', label: g.group, collapsible: true, collapsed: false, items: g.pages}));
  for (const g of tab.groups) pages.push(...g.pages);
}
for (const page of pages) {
  const src = path.join(SRC, `${page}.mdx`);
  const dst = path.join(DOCS, `${page}.mdx`);
  fs.mkdirSync(path.dirname(dst), {recursive: true});
  fs.writeFileSync(dst, transform(fs.readFileSync(src, 'utf8'), page));
}

rm(path.join(SITE, 'static/images'));
rm(path.join(SITE, 'doc-assets'));
// Kept outside static/ so images are bundled once (hashed) instead of copied twice
copyDir(path.join(SRC, 'images'), path.join(SITE, 'doc-assets/images'));
copyDir(path.join(SRC, 'logo'), path.join(SITE, 'static/logo'));
fs.copyFileSync(path.join(SRC, 'favicon.png'), path.join(SITE, 'static/favicon.png'));

fs.writeFileSync(path.join(SITE, 'sidebars.js'),
  `// Generated by tools/sync-docusaurus.mjs from mintlify/docs.json. Do not edit by hand.\nexport default ${JSON.stringify(sidebars, null, 2)};\n`);
fs.writeFileSync(path.join(SITE, 'src/generated-nav.json'), JSON.stringify({
  tabs: tabIds,
  redirects: (cfg.redirects || []).map((r) => ({from: r.source, to: r.destination})),
}, null, 2));
console.log(`Synced ${pages.length} pages, ${tabIds.length} sidebars, ${(cfg.redirects || []).length} redirects.`);
